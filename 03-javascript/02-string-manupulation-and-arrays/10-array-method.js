// pop and push
let cars = ["audi", "bmw", "xuv", "maruti"];
console.log(cars.push("toyota")); // pushes in the end
console.log(cars.push("ferrari"));

cars.pop(); //delete elements from the last of array

// shift and unshift
let toys = ["gun", "ps5", "xbox", "nitendo box"];
console.log(toys.unshift("lego set")); // add item in the start of an array

toys.shift(); // delete items from the start of an array
